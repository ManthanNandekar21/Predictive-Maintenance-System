"""
report_generator.py
Creates CSV and PDF prediction reports.
"""
import io
import csv
import datetime
import pandas as pd


def to_csv_bytes(history: list[dict]) -> bytes:
    """Serialise the prediction history list to CSV bytes."""
    if not history:
        return b""
    fieldnames = list(history[0].keys())
    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=fieldnames)
    writer.writeheader()
    writer.writerows(history)
    return buf.getvalue().encode()


def build_report_dict(inputs: dict, prediction: dict,
                       diagnosis: dict, shap_result: dict,
                       recommendations: dict) -> dict:
    """Flatten one prediction into a single dict row for CSV history."""
    now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    row = {
        "Timestamp"         : now,
        "Product Type"      : inputs.get("product_type", ""),
        "Air Temp [K]"      : inputs.get("air_temp", ""),
        "Process Temp [K]"  : inputs.get("proc_temp", ""),
        "RPM"               : inputs.get("rpm", ""),
        "Torque [Nm]"       : inputs.get("torque", ""),
        "Tool Wear [min]"   : inputs.get("tool_wear", ""),
        "Prediction"        : prediction.get("label", ""),
        "Failure Prob (%)"  : round(prediction.get("prob_failure", 0) * 100, 2),
        "Risk Level"        : prediction.get("risk_level", ""),
        "Subtypes"          : ", ".join(diagnosis.get("subtypes", [])) or "None",
        "Priority"          : recommendations.get("priority", ""),
        "Top SHAP Feature"  : (shap_result["top5"][0]["display"]
                                if shap_result.get("available") and shap_result.get("top5")
                                else "N/A"),
        "Recommendations"   : " | ".join(recommendations.get("actions", [])),
    }
    return row


def to_pdf_bytes(report_dict: dict, shap_bar_png: bytes = None) -> bytes:
    """
    Generate a simple text-based PDF.
    Uses reportlab if available; falls back to a plain-text PDF skeleton.
    """
    try:
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib.units import cm
        from reportlab.lib import colors
        from reportlab.platypus import (SimpleDocTemplate, Paragraph,
                                         Spacer, Table, TableStyle, Image as RLImage)

        buf = io.BytesIO()
        doc = SimpleDocTemplate(buf, pagesize=A4,
                                  leftMargin=2*cm, rightMargin=2*cm,
                                  topMargin=2*cm, bottomMargin=2*cm)
        styles = getSampleStyleSheet()
        title_style = ParagraphStyle('title', parent=styles['Title'],
                                       fontSize=16, spaceAfter=12)
        h2_style    = ParagraphStyle('h2', parent=styles['Heading2'],
                                       fontSize=12, spaceAfter=6)
        body_style  = styles['Normal']

        story = []
        story.append(Paragraph("AI-Based Industrial Predictive Maintenance", title_style))
        story.append(Paragraph("Prediction Report", styles['Heading2']))
        story.append(Spacer(1, 0.3*cm))

        # Table of inputs + results
        data = [["Field", "Value"]]
        for k, v in report_dict.items():
            data.append([str(k), str(v)])
        t = Table(data, colWidths=[7*cm, 10*cm])
        t.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#16213e')),
            ('TEXTCOLOR',  (0,0), (-1,0), colors.white),
            ('FONTNAME',   (0,0), (-1,0), 'Helvetica-Bold'),
            ('ROWBACKGROUNDS', (0,1), (-1,-1),
             [colors.HexColor('#f5f5f5'), colors.white]),
            ('GRID',  (0,0), (-1,-1), 0.5, colors.HexColor('#cccccc')),
            ('FONTSIZE', (0,0), (-1,-1), 9),
            ('PADDING', (0,0), (-1,-1), 6),
        ]))
        story.append(t)
        story.append(Spacer(1, 0.5*cm))

        if shap_bar_png:
            story.append(Paragraph("SHAP Feature Contributions", h2_style))
            img_buf = io.BytesIO(shap_bar_png)
            img = RLImage(img_buf, width=15*cm, height=8*cm)
            story.append(img)

        story.append(Spacer(1, 0.5*cm))
        story.append(Paragraph(
            "<i>Disclaimer: This report is generated by an ML model and represents "
            "a probabilistic estimate. It does not replace a certified engineering inspection.</i>",
            ParagraphStyle('small', parent=body_style, fontSize=7,
                           textColor=colors.grey)))

        doc.build(story)
        buf.seek(0)
        return buf.getvalue()

    except ImportError:
        # Fallback: minimal PDF (plain text wrapped in PDF skeleton)
        lines = ["AI-Based Industrial Predictive Maintenance — Prediction Report", ""]
        for k, v in report_dict.items():
            lines.append(f"{k}: {v}")
        text = "\n".join(lines)
        # Build the most minimal valid PDF manually
        obj1 = b"1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n"
        obj2 = b"2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n"
        stream = text.encode("latin-1", errors="replace")
        obj4 = (b"4 0 obj\n<< /Length " + str(len(stream)).encode() +
                b" >>\nstream\n" + stream + b"\nendstream\nendobj\n")
        obj3 = (b"3 0 obj\n<< /Type /Page /Parent 2 0 R "
                b"/MediaBox [0 0 595 842] /Contents 4 0 R "
                b"/Resources << >> >>\nendobj\n")
        header = b"%PDF-1.4\n"
        body   = obj1 + obj2 + obj3 + obj4
        xref_offset = len(header) + len(body)
        pdf = (header + body +
               b"xref\n0 5\n0000000000 65535 f \n" +
               b"trailer\n<< /Size 5 /Root 1 0 R >>\n" +
               b"startxref\n" + str(xref_offset).encode() + b"\n%%EOF\n")
        return pdf
